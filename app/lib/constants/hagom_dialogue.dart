  /// 순차적 복약 완료 토스트 반환
  static Map<String, String> getRandomMedToast(String medName) {
    final item = medCompletionToasts[_toastSeqIndex % medCompletionToasts.length];
    _toastSeqIndex++;
    return {
      'title': item['title']!,
      'message': '$medName ${item['message']!}',
    };
  }

  /// 순차적 헤더 말풍선 반환
  static String getRandomHeaderQuote() {
    final q = headerBubbleQuotes[_headerSeqIndex % headerBubbleQuotes.length];
    _headerSeqIndex++;
    return q;
  }

  /// 순차적 룸 대사 반환
  static String getRandomRoomQuote(String? previousQuote) {
    final q = roomQuotes[_roomSeqIndex % roomQuotes.length];
    _roomSeqIndex++;
    return q;
  }

  /// 모드별 랜덤 토크 반환 (테스트 및 실제 발송용)
  static String getTalkQuoteByFrequency(String frequency) {
    if (frequency == '적극적') {
      // 적극적 모드: 일반 토크 + 매콤한 토크 혼합 풀
      final combined = [...generalTalkQuotes, ...spicyTalkQuotes];
      final q = combined[_spicyTalkIndex % combined.length];
      _spicyTalkIndex++;
      return q;
    } else {
      // 기본 모드: 다정한 일반 토크 풀
      final q = generalTalkQuotes[_generalTalkIndex % generalTalkQuotes.length];
      _generalTalkIndex++;
      return q;
    }
  }
